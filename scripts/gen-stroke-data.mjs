import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'src/data/lessons.js'), 'utf8');
const set = new Set(src.match(/[\u4E00-\u9FFF]/g) ?? []);
const chars = [...set].sort();

const lines = chars.map(
  (c) => `  '${c}': () => import('kanji-writer-data-jp/${c}.json'),`,
);

const out = `// Generated by scripts/gen-stroke-data.mjs — ${chars.length} kanji
export const STROKE_CHAR_LOADERS = {
${lines.join('\n')}
};

export function hasStrokeData(char) {
  return Object.prototype.hasOwnProperty.call(STROKE_CHAR_LOADERS, char);
}

export function kanjiCharDataLoader(char, onLoad, onError) {
  const load = STROKE_CHAR_LOADERS[char];
  if (!load) {
    onError(new Error(\`Không có dữ liệu nét: \${char}\`));
    return;
  }
  load()
    .then((mod) => onLoad(mod.default ?? mod))
    .catch(onError);
}
`;

writeFileSync(join(root, 'src/utils/kanjiStrokeData.js'), out);
console.log(`Wrote ${chars.length} kanji stroke loaders`);
